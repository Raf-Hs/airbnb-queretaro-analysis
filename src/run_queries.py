"""Execute every analysis query and write a readable results appendix.

Output: reports/sql_results.md
"""

from __future__ import annotations

import re
import sqlite3
from datetime import datetime, timezone

import pandas as pd

from config import DB_PATH, REPORTS_DIR, SQL_DIR

QUERY_FILE = SQL_DIR / "03_analysis_queries.sql"
OUTPUT = REPORTS_DIR / "sql_results.md"

HEADER = re.compile(r"^-- name:\s*(\S+)\s*$", re.MULTILINE)
DESC = re.compile(r"^-- description:\s*(.+)$", re.MULTILINE)


def parse_queries(text: str) -> list[dict]:
    matches = list(HEADER.finditer(text))
    queries = []
    for i, match in enumerate(matches):
        start = match.end()
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        block = text[start:end]
        desc_match = DESC.search(block)
        sql = DESC.sub("", block).strip()
        sql = re.sub(r"^--.*$", "", sql, flags=re.MULTILINE).strip()
        sql = sql.rstrip(";").strip()
        queries.append(
            {
                "name": match.group(1),
                "description": desc_match.group(1).strip() if desc_match else "",
                "sql": sql,
            }
        )
    return queries


def _fmt(value, numeric: bool) -> str:
    if pd.isna(value):
        return ""
    if numeric:
        fv = float(value)
        if abs(fv) >= 10 and fv.is_integer():
            return f"{fv:,.0f}"
        if abs(fv) >= 10:
            return f"{fv:,.1f}"
        return f"{fv:.3f}".rstrip("0").rstrip(".")
    return str(value).replace("|", "\\|")


def to_markdown(df: pd.DataFrame) -> str:
    """Render a compact GitHub-flavoured table with right-aligned numbers.

    pandas.to_markdown() re-parses formatted numbers (turning 11,995,861 into
    scientific notation) and needs the optional `tabulate` package, so this
    small renderer keeps the output deterministic.
    """
    if df.empty:
        return "_No rows returned._"

    headers = [str(c) for c in df.columns]
    numeric = [bool(pd.api.types.is_numeric_dtype(df[c])) for c in df.columns]
    rows = [[_fmt(v, numeric[i]) for i, v in enumerate(rec)] for rec in df.itertuples(index=False, name=None)]

    widths = [
        max([len(h)] + [len(r[i]) for r in rows] + [3])
        for i, h in enumerate(headers)
    ]

    def render(cells: list[str]) -> str:
        padded = [
            cell.rjust(widths[i]) if numeric[i] else cell.ljust(widths[i])
            for i, cell in enumerate(cells)
        ]
        return "| " + " | ".join(padded) + " |"

    separator = "|" + "|".join(
        ("-" * (w - 1) + ":") if numeric[i] else (":" + "-" * (w - 1))
        for i, w in enumerate(widths)
    ) + "|"

    lines = [render(headers), separator]
    lines.extend(render(row) for row in rows)
    return "\n".join(lines)


def main() -> None:
    text = QUERY_FILE.read_text(encoding="utf-8")
    queries = parse_queries(text)
    if not queries:
        raise RuntimeError(f"No queries found in {QUERY_FILE}")

    con = sqlite3.connect(DB_PATH)
    lines = [
        "# SQL analysis results",
        "",
        "Generated by `src/run_queries.py` from `sql/03_analysis_queries.sql`.",
        f"Database: `{DB_PATH.name}` · run {datetime.now(timezone.utc):%Y-%m-%d %H:%M UTC}",
        "",
        "Scope: `v_city_listings` (99 listings) excludes one rural farm stay 47 km",
        "from the centro. Money is MXN. `occupancy` is calendar occupancy unless",
        "labelled otherwise.",
        "",
    ]
    try:
        for query in queries:
            df = pd.read_sql_query(query["sql"], con)
            lines.append(f"## `{query['name']}`")
            lines.append("")
            if query["description"]:
                lines.append(f"_{query['description']}_")
                lines.append("")
            lines.append(to_markdown(df))
            lines.append("")
            print(f"{query['name']:<38} {len(df):>3} rows")
    finally:
        con.close()

    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"\nwrote {OUTPUT} ({len(queries)} queries)")


if __name__ == "__main__":
    main()
